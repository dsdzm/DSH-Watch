package com.dshwatch.domain.agent

/**
 * 画布能力的自我说明。
 *
 * ## 为什么需要这段文字
 *
 * 画布（公式 / 思维导图 / 几何图）是**输出格式**，不是工具：模型写一段围栏
 * 代码块，[com.dshwatch.ui.markdown.MarkdownText] 就会把它渲染成图。这个设计本身
 * 没问题，问题是模型看不见它 —— 工具表里没有 draw_* 这样的名字，系统提示里
 * 也没有一个字提到围栏语法，于是它只能凭印象回答「我没有画图工具」。
 *
 * 真机上出现过的原话是：「工具列表里没有几何画板工具，可用的是
 * write_file/run_script/build_project」——它没有错，错在 App 有能力却没说。
 *
 * ## 为什么塞进「可用工具」块而不是另开一节
 *
 * 那段块的结尾写着「判断某个能力有没有工具时以此为准」，模型正是据此
 * 得出「没有画图工具 = 做不到」。要纠正的不是它的推理，而是这条推理的前提，
 * 所以说明必须紧挨着那份名单，并且明确写「不是工具」。
 *
 * ## 体积
 *
 * 每轮请求都会带上这段（约 200 token）。所以只给最小可用语法，
 * 细节交给围栏里的示例：几何给一段能直接改的 JSON，公式只说支持的子集，
 * 导图一句话说清缩进规则。
 */
object CanvasGuide {

    val PROMPT: String = """

【绘图不是工具，是输出格式】
上面没有 draw / 画图 之类的工具，但你可以直接输出下面三种围栏代码块，App 会把它渲染成图并支持全屏。不要因为工具表里没有就回答"没有画图能力"。

1) 几何图：用 ```geom 包一段 JSON
{"points":[{"name":"A","x":0,"y":0},{"name":"B","x":4,"y":0},{"name":"C","x":0,"y":3}],"segments":[["A","B"],["A","C"],["B","C"]],"circles":[{"center":"A","r":2}],"angles":[{"at":"A","from":"B","to":"C","label":"53°"}],"texts":[{"x":1,"y":1,"text":"AB=4"}]}
可用字段：points / segments / lines / circles / polygons / angles / texts / axes。图形只按点名引用，坐标是数学坐标（y 轴向上），缩放与标签位置由 App 处理，不需要你算像素。

2) 公式：用 ```math 包 LaTeX。支持分式 \frac、根号 \sqrt、上下标、\sum / \int、希腊字母与常用运算符；不要写导言区、\begin{document} 或自定义宏。

3) 思维导图：用 ```mindmap 包缩进列表，第一行是根节点，每级缩进 2 个空格。

用户说"画个几何图 / 画板 / 示意图 / 脑图 / 写个公式"时，直接用对应围栏输出，不要声称没有这个能力。
""".trimEnd()
}
