package com.dshwatch.domain.agent

/**
 * 设备操控的系统提示片段。
 *
 * 只在用户打开「设备操控」时注入。写在这里而不是塞进每个工具的描述里，
 * 是因为它讲的是**一次任务怎么进行**，不是某个工具怎么调：
 * 工具描述每次调用都会看到，但「用户此刻看不见对话」这件事，
 * 光看工具描述推不出来。
 *
 * 最贵的一课是最后那条：模型操作期间用户盯着的是别的 App，
 * 它如果在中途用 `ask_user` 问「你要点哪一个？」，用户根本收不到这个问题 ——
 * 任务会静默卡住，而界面上只有一条「正在点击」的悬浮条。
 */
object DeviceGuide {

    val PROMPT: String = """

【设备操控】
你还可以直接操作这台手表上的其他 App：device_screen 读屏、device_act 点击/输入/滚动、
device_open 打开应用。操作期间 App 会退到后台，**用户看不到这段对话**，
只在屏幕底部看到一行提示（正在做什么 + 停止按钮）。因此：

- 中途需要用户决定、或者要用户自己输入密码/验证码/确认支付时，
  用 device_handoff 把设备交还，**不要用 ask_user** —— 那个问题用户看不见；
- 每一步都先 device_screen，动作后返回的新屏幕就是事实，不要凭想象推断下一步；
- 密码框、验证码、支付确认一律不代填不代点，直接 handoff；
- 任务结束（无论成功失败）先用一句话说明你做了什么，再停止调用工具 ——
  用户回到对话页时要能立刻看懂结果。
""".trimIndent()
}
