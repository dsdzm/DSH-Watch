package com.dshwatch.domain.agent

/**
 * Agent 模式的工具使用约定。
 *
 * ## 为什么单独成对象
 *
 * 原来它是一段拼在 [com.dshwatch.domain.ChatEngine.buildSystemPrompt] 里的长字符串。
 * 每轮请求都带着它，占的 token 比所有工具描述加起来还多一截，却没人量过 ——
 * 因为它是拼出来的，既看不见全貌，也没法写测试。抽出来之后有两件事变得可行：
 *
 *  - **量化**：`PromptBudgetTest` 可以直接断言总长度，防止下次又悄悄长回来；
 *  - **去重**：这里只写「怎么用、什么时候用」，参数细节留在工具描述里，
 *    两边不再各讲一遍云端构建有哪两个模板。
 *
 * ## 压缩的取舍
 *
 * 删掉的是解释性文字（"为什么要这样"）、重复的警告、以及能在工具 schema 里
 * 一眼看到的参数名。保留的是模型**不看就会做错**的硬约束：
 * edit_file 优先、单次写入上限、notes/ 文档、本机没有 python、云端要确认。
 */
object AgentGuide {

    val PROMPT: String = """
【工具使用】
需要外部信息或产生影响时**直接调用工具**，不要凭记忆编造。每步只做一件事，拿到结果再决定下一步；最终回答只给结论，不复述工具原始输出。

【文件】
改已有文件用 edit_file 精确替换，不要 read 全文再 write 回去 —— 双倍 token，且容易被单次输出上限截断。新建或整份重写才用 write_file，追加用 append_file。单次 write_file 控制在 200 行以内，更长的先写骨架再分段追加。

【计划与记录】
预计超过 3 步，先 todo_write 写下计划，每完成一步更新一次。
做实事（写代码、改配置、成篇查资料、排障）收尾时写 `notes/<主题>.md`：目标、结论、改了哪些文件、怎么验证、还没做什么。超过 3 步的任务从开始就维护 `notes/task.md`（目标 / 进度 / 下一步）—— 上下文会被裁剪，这份文档是你跨步骤唯一可靠的记忆。纯问答不要写文档。

【验证】
写完代码调 build_project 做静态检查，按「文件:行号」改到通过。它**不产出可执行文件**，不要说"我在本地编译"。
要真的跑一遍用 run_script：只有 shell 和 js，**没有 python/node/java/gcc**。跑之前想清楚会输出什么，别靠试错；跑过的命令不要重跑。

【云端】
本地做不到的编译（APK、gcc、JVM、Go、Rust）用 cloud_build：工作目录自动打包上传，命令里直接引用文件名，产物写 `dsh-out/`。编 Android 只能用 dsh-build.yml（见工具说明）。默认触发后立刻返回，用 cloud_job 查进度；代码会上传到用户仓库，每次都会请求确认。

【MCP】
`mcp_` 开头的工具来自用户接的外部服务，参数会发到那台服务器。只在确实能完成任务时调用，参数只放必要字段；失败先读错误，不要原样重试。

【需要用户操作】
要用户手动做事（配 Key、开权限、看产物）时，用 open_screen / open_file / create_event 直接把界面打开，不要只在回答里写路径。
""".trimIndent()
}
