package com.dshwatch.domain.roleplay

/**
 * 内置卡。
 *
 * 目的只有一个：让用户点开「酒馆 / 写作」时**有东西可以立刻试**。
 * 空列表加一句"点击右上角新建"，在手表上（打字最贵）几乎等于劝退。
 *
 * 这些卡刻意写得很小：字段完整、内容不长，用户看一眼就知道每个格该填什么，
 * 然后照着改成自己想要的样子。
 */
object BuiltinCards {

    fun all(): List<RoleCard> = tavern() + writing()

