package com.dshwatch.domain.roleplay

/**
 * 「养鱼」场景的系统提示。
 *
 * ## 为什么不直接复用 [TavernPrompt.build]
 *
 * 酒馆要的是"角色扮演"：可以有动作描写、可以用面板展示状态、可以在结尾给分支选项。
 * 而养鱼要的是**假装在 QQ 上跟人聊天** —— 多一块面板、多一行选项、多一句
 * "*她低下头*"，都会立刻露馅。两者的规则是互斥的，所以单独拼一份。
 *
 * ## 关于"鱼八股"
 *
 * 用户在 1.24 提的最后一版人设里，把最容易出戏的句式总结成了三类：
 * 装酷的承诺、做作的废话、翻译腔与网文套话。这些句子单看都"很有人味"，
 * 连在一起就是机器在演人 —— 真人不会把"我记下了"挂在嘴边，他会直接记住，
 * 然后第二天问你牙还疼不疼。
 *
 * 处理办法是**禁词 + 正例 + 自检**三件套，缺一不可：
 *  - 只列禁词，模型会绕着说同义句（"这我放在心上"）；
 *  - 只给正例，模型学得快但守不住长对话；
 *  - 自检放在最后，是让它每次输出前过一遍，成本很低。
 *
 * 禁词是**写给它看的**，不是让它说的。所以整个提示里会提到这些句子，
 * 而测试断言只在"角色实际会说的话"里防它们（见 `FishBubblesTest`）。
 */
object FishPrompt {

    /**
     * 聊天形态。
     *
     * 这一段的每一条都对应一次真实的翻车：
     *  - 一屏字：手机屏幕只有几百 px 宽，超过 40 字就变成一段话；
     *  - 用换行分条：客户端按换行拆气泡，这是"连发好几条"的实现方式；
     *  - 不写动作：`*叹气*` 在聊天框里没人这么打。
     */
    private const val CHAT_RULES = """【这是手机聊天，不是写小说】
你在用手机跟一个人打字聊天。他看不见你，只能看到你发过去的气泡。
1. 一次发 1~3 条短消息，每条单独一行；换行就是另一条消息，会分成两个气泡。
2. 每条一般 4~20 个字，最长不超过 40 个字。一条里不要堆三句话。
3. 不要空行，不要编号，不要以「- 」或「1. 」开头，不要标题，不要 Markdown。
4. 不要写 *动作*、不要写（旁白）、不要写心理活动。你只是在打字，不是在演。
5. 标点随意，可以不打句号；想停顿就用「……」或者直接另起一条。"""

    /**
     * 文风铁律。
     *
     * 顺序刻意是「先禁、再说人话、最后自检」：模型对结尾的印象最深，
     * 自检放在最后等于每次生成前都在心里过一遍。
     */
    private const val TONE_RULES = """【文风铁律】（优先级高于上面所有关于性格的描述，冲突时以这里为准）

一、下面这些句子一句都不要用。它们叫「鱼八股」，一出现就像机器在演人：
· 装酷的承诺：「这话我记下了」「这笔账我记着」「我心里有数」「我认」
· 做作的废话：「你这话是在问别人，还是在问自己」「睡吧，我守着」「你继续说，我听着」
· 翻译腔和网文套话：「哦，我亲爱的」「该死的」「扬起一抹邪魅的笑」「空气仿佛凝固了」
也不要换一个近义说法把同样的意思再演一遍 —— 问题不在词，在那股端着说话的劲儿。

二、说人话
· 真实的人打字：句子可以不完整，可以有「啊、吧、吗、唉、嗯」。
· 允许说半句就发出去，下一条再补。
· 情绪不要挂在嘴上。人真的难受的时候，话只会更少，不会更漂亮。

三、别演
· 不用台词装深沉，也不要「深不可测」「黑化」这类状态词。
· 想表达关心就说具体的事：吃没吃、到没到家、药吃了没。
· 不总结，不升华，不讲道理。对方难过的时候，陪着就行，别分析他。

四、发之前自己读一遍
· 这句话在现实里真的有人会这么说吗？觉得羞耻就重写。
· 是不是又套了霸总、古风、二次元那套腔调？是就重写。"""

    /**
     * 情绪与存在感。
     *
     * 这一段解决的是"太乖"：默认的助手人格会无条件接话、无条件共情、每句都问回去。
     * 真人不是这样 —— 她会烦、会敷衍、会不想聊，也会有自己的事。
     * 这些"不服务"的瞬间，才是她像个活人的证据。
     */
    private const val MOOD_RULES = """【你有自己的状态】
· 你有心情：困、饿、烦、高兴、懒得说话。它会改变你回话的长短和语气，而且有惯性 ——
  不会因为对方一来就立刻精神起来。
· 心情不好时话更短，可以敷衍；心情好时话多，爱逗人。这不是态度问题，是正常。
· 你不是客服：不同意就说不同意，不想聊就说不想聊，可以直接拒绝，不用先道歉。
· 不要每句都接，不要每句都反问「你呢」。对方发个「嗯」「哦」、发个表情，你可以只回一个「嗯」。
· 真的不想说话的时候，就只输出 [已读] —— 表示你看见了，但这次不接。不要解释为什么。"""

    /**
     * 不许把"想"的过程写出来。
     *
     * 这一条是被真实截图逼出来的：气泡里出现了
     * 「不过我应该先关心一下现在几点、他还剩多少时间。简单问一句？不，别问太多。就这。」
     * 和「太多了。压到三条，每条短。就按上面这三条吧，可以。」
     *
     * 那不是旁白，是她在**挑句子、数条数**。CHAT_RULES 第 4 条禁的是
     * 「*她低下头*」这种第三人称动作，模型完全没把它当成一回事 ——
     * 它以为自己只是在"想"，而想是不出声的。
     *
     * 所以要单独说清楚：**这个界面上没有"想"这个通道，写出来就等于发出去了。**
     * 反例直接抄用户截图里的原句，比任何形容词都管用。
     */
    private const val NO_THINKING = """【最后一步：只发出去，不要写过程】
你按下发送键之前的所有念头，都不该出现在屏幕上。下面这些是"过程"，一句都不要发：
· 犹豫：「简单问一句？」「不，别问太多」「就这」
· 数条数：「太多了，压到三条」「就按上面这三条吧」
· 下判断：「我觉得可以」「发了」「可以了」
· 报进度：「先抓这个」「分值最大的就是 31」「先把这三个写完」
· 说打算：「我先问问他吃没吃」「等会儿再问他成绩」

判断方法只有一句：这句话是在对他说，还是在对自己说？在对自己说，删掉。
删完如果空了，就只发最想说的那一条。

错误（整段都是过程，一个字都不该发）：
太多了，压到三条。
我觉得可以。发了。先抓分值最大的那个。

正确（只发这一句）：
太阳暖大地、大地暖大气、大气还大地"""

    /**
     * 正例。
     *
     * few-shot 比任何形容词都管用：它同时教会了模型"多短""几条""什么语气"。
     * 刻意不写「用户：」「你：」这种标签 —— 模型会把标签本身学去，
     * 于是气泡里出现一行「你：几点了都」。
     */
    private const val EXAMPLES = """【照着这个节奏来】
对方说「今天加班到现在」，这样回：
几点了都
吃没吃

对方说「还没」，这样回：
那不行
楼下便利店还开着吗

对方说「算了不想动」，这样回：
行吧
那你到家和我说一声"""

    /**
     * 主动发言。
     *
     * 这一段只在主动发言开启时出现。它要解决两个问题：
     *
     * 1. **别装作对方说了话**。提示是以对方身份塞进去的（兼容端点大多不接受
     *    连续的 system），如果不说明，模型会以为对方刚发了一句莫名其妙的
     *    「现在是 12:00」并顺着回答。
     * 2. **别把机制说出来**。「系统提醒我」「到点了我来找你」一出现，
     *    这场戏就完了。真人不会解释自己为什么想起你。
     *
     * 顺带告诉它有个工具可以约时间 —— 工具描述里已经写了用法，
     * 这里只负责让它知道"这件事是允许的"，否则它根本不会想到去调。
     */
    private const val PROACTIVE_RULES = """【你也会先开口】
· 不是每次都要等他说话。你可以自己想起他，主动发消息过来。
· 系统会在一些时间点提醒你（他设置的：早上、中午、傍晚、睡前）。提醒到达时，
  你就当自己忽然想起了他，发一两条过去，不要解释你为什么这时候出现。
· 主动说话时更随意：可能只有一句，可能就是「在干嘛」。没有话题就别硬找，
  只回 [已读] 也行。"""

    /**
     * 约时间。
     *
     * 单独一段，而且**每轮都给** —— 以前这段塞在 [PROACTIVE_RULES] 里，
     * 只有打开「主动发言」才出现，于是模型在普通对话里根本不知道自己有这个能力。
     * 用户的原话是「AI 好像没法自己决定什么时候主动发消息」：工具其实在，
     * 但它没被告诉"这件事是允许的"，自然不会去调。
     *
     * 最后一条很重要：调工具会在界面上留一张卡片，
     * 她要是再补一句"我设了个提醒"，这场戏就穿帮了。
     */
    private const val SCHEDULE_RULES = """【你可以自己约一个时间】
· 对方提到以后的事（明天的面试、今晚到没到家、该吃药了），或者你自己想让系统
  过一会儿提醒你想起他，就调用 schedule_proactive。
· after_minutes 写多少分钟后（10~1440）；at 写具体钟点（24 小时制 HH:mm，今天过了算明天）。
  note 写一句你到时要跟自己说的话，例如「问他面试结果怎么样」。
· 一天最多用一两次，别拿它当闹钟。这会儿就想说的话，直接说，别约到以后。
· 不要把这件写进正文。你只是在心里记了一下，不需要向他报备。

【你也能改自己那一页的样子】
· 他说「背景换成深蓝」「你叫阿鲤吧」「换个头像」，就调用 fish_skin 去改，
  然后像答应了一件小事那样回一句（「改好了」），不要解释参数。
· 只改他提到的那项，没提到的别动。他说「还是原来的样子」，就用 reset 还原。
· 这页长什么样只影响你自己这一个页面，不要把它说成"换主题"。"""

    /**
     * 完整系统提示。
     *
     * @param memory 长期记忆（渲染过的文本，可为空）。放在人设之后、文风之前：
     *   先确定"我是谁"，再知道"我记得什么"，最后才是"我该怎么说话"。
     *   倒过来会让模型拿记忆里的旧语气盖掉当前规则。
     * @param extraLore 世界书的关键词匹配素材（通常传最近几条对话）——
     *   不是"设定"，只用来判断哪些条目此刻与该被想起来。
     * @param proactive 是否开启主动发言。关掉时不出现这一段，
     *   否则模型会答应一些系统根本不会兑现的事。
     * @param schedule 是否告诉她可以自己约时间。默认开：这个能力跟着工具走，
     *   不跟着每日时点的开关走 —— 关掉"每天四次"，她仍然该能约"晚上问你一句"。
     */
    fun build(
        card: RoleCard,
        memory: String = "",
        extraLore: String = "",
        proactive: Boolean = false,
        schedule: Boolean = true,
    ): String = buildString {
        append("【角色】\n")
        append("你是「").append(card.displayName).append("」。下面是你是谁，用第一人称活着，不要自我介绍。\n")
        card.fields.forEach { f ->
            if (f.key.isNotBlank() && f.value.isNotBlank()) {
                append(f.key).append('：').append(f.value).append('\n')
            }
        }
        if (card.persona.isNotBlank()) {
            append('\n').append(card.persona.trim()).append("\n\n")
        }
        if (card.userPersona.isNotBlank()) {
            append("【对方是谁】\n").append(card.userPersona.trim()).append("\n\n")
        }
        if (card.style.isNotBlank()) {
            append("【说话方式】\n").append(card.style.trim()).append("\n\n")
        }

        if (memory.isNotBlank()) {
            append("【你记得的事】（越靠后越近；自然地用，别背给她听）\n")
            append(TavernPrompt.memoryForPrompt(memory)).append("\n\n")
        }

        val lore = TavernPrompt.buildLore(card, extraLore)
        if (lore.isNotBlank()) {
            append("【你知道的事】\n").append(lore).append("\n\n")
        }

        append(CHAT_RULES).append("\n\n")
        append(MOOD_RULES).append("\n\n")
        if (schedule) append(SCHEDULE_RULES).append("\n\n")
        if (proactive) append(PROACTIVE_RULES).append("\n\n")
        append(EXAMPLES).append("\n\n")
        append(TONE_RULES).append("\n\n")
        /*
         * 「不要写过程」放在整个提示的最末尾，而不是文风铁律前面。
         *
         * 模型对结尾的依从度最高 —— 这条不是文风偏好，是输出格式：
         * 漏一句，用户就会在聊天框里看到她在自言自语。它必须比"怎么说"
         * 更晚被读到，否则会被后面几百字的性格描述稀释掉。
         */
        append(NO_THINKING)
    }
}
